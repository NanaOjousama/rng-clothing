# ---- witch s9 D (added after the user's reference packs, 2026-10-13) ---------------------------------------
# All 17 reference witch hats (experiments/witch_reference_packs_01) lean the side-view tip toward the BACK of
# the head (R view: tip left of centre, -0.5..-5 px).  Round-2 s9 leans it toward the face (+1.5).
# D = B with the crown rows (0-5) mirrored about the crown's centre column 9, so the tip curls backward.
def _lean_back(txt, rows=6, c=9):
    out = []
    for y, r in enumerate(txt.strip('\n').split('\n')):
        if y < rows:
            r = ''.join(r[2 * c - x] if 0 <= 2 * c - x < 20 else '.' for x in range(20))
        out.append(r)
    return '\n' + '\n'.join(out) + '\n'


